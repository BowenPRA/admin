const LangContext = createContext({ lang: 'en', setLang: () => {}, t: (k) => k })

export function LangProvider({ children }) {
  const [lang, setLangState] = useState(() => {
    try { return localStorage.getItem('pra-admin-lang') || 'en' } catch { return 'en' }
  })
  const setLang = useCallback((l) => {
    setLangState(l)
    try { localStorage.setItem('pra-admin-lang', l) } catch { /* ignore */ }
  }, [])
  // t('key') or t('key', { n: 3 }) to fill {n} in the string.
  const t = useCallback((key, vars) => {
    const s = STRINGS[key]
    if (!s) return key
    const text = lang === 'vi' ? s[1] : s[0]
    return vars ? text.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m)) : text
  }, [lang])
  return <LangContext.Provider value={{ lang, setLang, t }}>{children}</LangContext.Provider>
}

export function useT() {
  return useContext(LangContext)
}
